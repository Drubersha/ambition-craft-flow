-- Плановая выручка и ставка НДС для расчёта прибыли по методике
-- «Отчёта о выполнении бюджета» (1С):
--   прибыль = выручка без НДС − расходы
--   прибыль сверх плана = прибыль факт − (план выручки − план расходов)
--
-- Плановая выручка задаётся без НДС и на месяц: в отчёте это постоянная
-- величина (2 295 081,97 ₽ для базы Хлебозаводская).
--
-- Ставка НДС нужна, чтобы привести фактические поступления (они приходят с
-- НДС) к сопоставимому с планом виду. Признака «работает с НДС» у арендаторов
-- в системе нет, поэтому ставка общая на план — расчёт приблизительный.
ALTER TABLE public.budget_plans
  ADD COLUMN IF NOT EXISTS revenue_plan_monthly numeric(14, 2) NOT NULL DEFAULT 0,
  ADD COLUMN IF NOT EXISTS vat_rate numeric(5, 2) NOT NULL DEFAULT 0;

COMMENT ON COLUMN public.budget_plans.revenue_plan_monthly IS
  'Плановая выручка без НДС за месяц; 0 — план не задан, прибыль сверх плана не считается';
COMMENT ON COLUMN public.budget_plans.vat_rate IS
  'Ставка НДС в процентах для приведения поступлений к выручке без НДС; 0 — не применять';
