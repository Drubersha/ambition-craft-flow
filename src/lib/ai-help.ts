/**
 * Сигналы «объяснительного» вопроса. Без них вопрос считается запросом данных
 * («какая дебиторка у ИТК») и уходит обычным инструментам.
 */
const EXPLAIN_SIGNALS = [
  "почему",
  "зачем",
  "что такое",
  "что значит",
  "что за ",
  "как счита",
  "как получ",
  "откуда",
  "чем отлич",
  "не совпад",
  "не сход",
  "не бьет",
  "разниц",
  "разные",
  "разная",
];

/** Определяет тему справки; null — вопрос не про методику дашборда. */
export function matchHelpTopic(question: string): HelpEntry | null {
  const q = question.toLowerCase().replace(/ё/g, "е");
  if (!EXPLAIN_SIGNALS.some((s) => q.includes(s))) return null;
  for (const entry of HELP_ENTRIES) {
    if (entry.triggers.some((group) => group.every((frag) => q.includes(frag)))) {
      return entry;
    }
  }
  return null;
}
